"""Pure configuration generator; no Home Assistant imports or network requests."""

from __future__ import annotations

import os
import re
import tempfile
from collections import Counter
from copy import deepcopy
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

DOMAIN = "wled_yaha"
VERSION = "0.1.2"
DEFAULT_OUTPUT = "includes/yandex_smart_home_wled.yaml"
MARKER = "# Generated by WLED YaHA Exporter. Do not edit this file.\n"

# These are YaHA/Yandex scene identifiers, NOT WLED effect identifiers.
# Exact names are matched, ignoring case, punctuation, spaces and е/ё.
ALIASES: dict[str, list[str]] = {
    "alarm": ["Тревога", "Alarm"],
    "alice": ["Алиса", "Alice"],
    "candle": ["Свеча", "Candle"],
    "dinner": ["Ужин", "Dinner"],
    "fantasy": ["Фантазия", "Fantasy", "Радуга", "Rainbow"],
    "garland": ["Гирлянда", "Garland"],
    "jungle": ["Джунгли", "Jungle"],
    "movie": ["Кино", "Movie"],
    "neon": ["Неон", "Neon"],
    "night": ["Ночь", "Night", "Ночник"],
    "ocean": ["Океан", "Ocean"],
    "party": ["Вечеринка", "Party"],
    "reading": ["Чтение", "Reading"],
    "rest": ["Отдых", "Rest", "Спокойный", "Relax"],
    "romance": ["Романтика", "Romance"],
    "siren": ["Сирена", "Siren"],
    "sunrise": ["Рассвет", "Sunrise"],
    "sunset": ["Закат", "Sunset"],
}


def normalized(value: str) -> str:
    return "".join(c for c in value.casefold().replace("ё", "е") if c.isalnum())


@dataclass
class DeviceSnapshot:
    """A detached view of one exported light and its controller's preset select."""

    light: str
    name: str
    room: str | None = None
    preset_entity: str | None = None
    options: list[str] = field(default_factory=list)
    preset_ids: dict[int, str] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    online: bool = True
    preset_online: bool = True


def validate_scene_keys(mapping: dict[str, Any]) -> None:
    unknown = set(mapping) - set(ALIASES)
    if unknown:
        raise ValueError("Неизвестные режимы Алисы: " + ", ".join(sorted(unknown)))


def validate_settings(raw: Any) -> dict[str, Any]:
    """Validate YAML and service overrides without depending on HA schemas."""
    result = deepcopy({} if raw is None else raw)
    if not isinstance(result, dict):
        raise ValueError("wled_yaha должен содержать словарь настроек.")
    allowed = {
        "output_file",
        "include_entities",
        "exclude_entities",
        "scene_map",
        "preset_ids",
        "devices",
    }
    if unknown := set(result) - allowed:
        raise ValueError("Неизвестные настройки: " + ", ".join(sorted(unknown)))
    output = result.setdefault("output_file", DEFAULT_OUTPUT)
    if not isinstance(output, str):
        raise ValueError("output_file должен быть строкой.")
    validate_relative_path(output)
    for key in ("include_entities", "exclude_entities"):
        values = result.setdefault(key, [])
        if not isinstance(values, list) or any(
            not isinstance(v, str) or not re.fullmatch(r"light\.[a-z0-9_]+", v)
            for v in values
        ):
            raise ValueError(f"{key}: требуется список entity ID вида light.example.")

    def validate_maps(part: dict[str, Any]) -> None:
        names = part.setdefault("scene_map", {})
        ids = part.setdefault("preset_ids", {})
        for value in (names, ids):
            if not isinstance(value, dict):
                raise ValueError("scene_map и preset_ids должны быть словарями.")
            validate_scene_keys(value)
        for key, value in list(names.items()):
            if isinstance(value, str):
                value = [value]
                names[key] = value
            if not isinstance(value, list) or any(
                not isinstance(v, str) or not normalized(v) for v in value
            ):
                raise ValueError(
                    f"scene_map.{key}: требуется имя или список имён пресетов."
                )
        for key, value in ids.items():
            if value is not None and (type(value) is not int or not 1 <= value <= 250):
                raise ValueError(
                    f"preset_ids.{key}: требуется номер от 1 до 250 или null."
                )

    validate_maps(result)
    devices = result.setdefault("devices", {})
    if not isinstance(devices, dict):
        raise ValueError("devices должен быть словарём по entity ID светильников.")
    for entity, part in devices.items():
        if not isinstance(entity, str) or not re.fullmatch(
            r"light\.[a-z0-9_]+", entity
        ):
            raise ValueError(f"Некорректный entity ID в devices: {entity!r}.")
        if not isinstance(part, dict) or set(part) - {
            "name",
            "room",
            "scene_map",
            "preset_ids",
        }:
            raise ValueError(f"Некорректные настройки devices.{entity}.")
        for key in ("name", "room"):
            if key in part and (
                not isinstance(part[key], str) or not part[key].strip()
            ):
                raise ValueError(
                    f"devices.{entity}.{key} должен быть непустой строкой."
                )
        validate_maps(part)
    return result


def resolve_scenes(
    snapshot: DeviceSnapshot,
    scene_names: dict[str, list[str]],
    preset_ids: dict[str, int | None],
) -> tuple[dict[str, str], list[str], list[str]]:
    """Map Yandex scenes to unique actual preset names; never infer IDs by order."""
    validate_scene_keys(scene_names)
    validate_scene_keys(preset_ids)
    warnings: list[str] = []
    errors: list[str] = []
    result: dict[str, str] = {}
    duplicates = Counter(snapshot.preset_ids.values() or snapshot.options)
    options = list(dict.fromkeys(snapshot.options))
    for scene in ALIASES:
        chosen: str | None = None
        if scene in preset_ids:
            preset_id = preset_ids[scene]
            if preset_id is None:  # Explicitly disable a global assignment.
                continue
            chosen = snapshot.preset_ids.get(preset_id)
            if chosen is None:
                errors.append(
                    f"{snapshot.light}: для {scene} задан ID {preset_id}, "
                    "но такой пресет не найден в данных WLED."
                )
                continue
        else:
            aliases = {normalized(n) for n in scene_names[scene]}
            matches = [n for n in options if normalized(n) in aliases]
            if len(matches) > 1:
                warnings.append(
                    f"{snapshot.light}: несколько пресетов подходят для {scene}: "
                    f"{matches}. Укажи один через scene_map или preset_ids."
                )
                continue
            if matches:
                chosen = matches[0]

        if chosen is None:
            continue
        if chosen not in options:
            errors.append(
                f"{snapshot.light}: пресет {chosen!r} отсутствует в options "
                f"{snapshot.preset_entity}; перезагрузи интеграцию WLED и повтори экспорт."
            )
            continue
        if duplicates[chosen] > 1:
            errors.append(
                f"{snapshot.light}: несколько пресетов называются {chosen!r}. "
                "Дай им разные имена: выбор через HA работает по имени."
            )
            continue
        if chosen in result.values():
            errors.append(
                f"{snapshot.light}: пресет {chosen!r} назначен нескольким режимам Алисы."
            )
            continue
        result[scene] = chosen
    return result, warnings, errors


def build_export(
    snapshots: list[DeviceSnapshot], settings: dict[str, Any]
) -> tuple[dict[str, Any], list[dict[str, Any]], list[str], list[str]]:
    """Return the YaHA fragment plus diagnostics, preserving no stale entries."""
    validate_scene_keys(settings.get("scene_map", {}))
    validate_scene_keys(settings.get("preset_ids", {}))
    entities: dict[str, Any] = {}
    reports: list[dict[str, Any]] = []
    warnings: list[str] = []
    errors: list[str] = []
    for snapshot in snapshots:
        device = settings.get("devices", {}).get(snapshot.light, {})
        scene_names = {
            **ALIASES,
            **settings.get("scene_map", {}),
            **device.get("scene_map", {}),
        }
        ids = {**settings.get("preset_ids", {}), **device.get("preset_ids", {})}
        if snapshot.preset_entity:
            scenes, scene_warnings, scene_errors = resolve_scenes(
                snapshot, scene_names, ids
            )
        else:
            scenes, scene_warnings, scene_errors = {}, [], []
            if any(value is not None for value in ids.values()):
                scene_errors.append(
                    f"{snapshot.light}: задан preset_ids, но нет выбора пресетов."
                )

        if not snapshot.online or not snapshot.preset_online:
            # Missing live catalog data must never prevent exporting the light.
            # Keep the configured IDs; unresolved scenes are retried on reconnect.
            if scene_errors:
                scene_warnings.append(
                    f"{snapshot.light}: экспортируем гирлянду с известными сценами; остальные сохранённые назначения повторно проверятся, когда WLED загрузит каталог пресетов."
                )
                scene_warnings.extend(scene_errors)
            scene_errors = []
        warnings.extend(snapshot.warnings + scene_warnings)
        errors.extend(snapshot.errors + scene_errors)
        config: dict[str, Any] = {
            "name": device.get("name", snapshot.name),
            "type": "light.garland",
            "color_profile": "natural",
        }
        room = device.get("room", snapshot.room)
        if room:
            config["room"] = room
        if scenes:
            config["modes"] = {"scene": scenes}
            config["custom_modes"] = {
                "scene": {
                    "state_entity_id": snapshot.preset_entity,
                    "set_mode": {
                        "action": "select.select_option",
                        "target": {"entity_id": snapshot.preset_entity},
                        "data": {"option": "{{ mode }}"},
                    },
                }
            }
        else:
            # Do not accidentally export unrelated built-in effects as preset modes.
            config["custom_modes"] = {"scene": False}
        entities[snapshot.light] = config
        unmapped = [n for n in snapshot.options if n not in scenes.values()]
        if unmapped:
            warnings.append(
                f"{snapshot.light}: не назначены режимам Алисы: {unmapped}. "
                "При необходимости назначь сцены в параметрах WLED YaHA."
            )
        reports.append(
            {
                "light": snapshot.light,
                "name": config["name"],
                "room": room,
                "preset_entity": snapshot.preset_entity,
                "presets": {str(k): v for k, v in sorted(snapshot.preset_ids.items())},
                "options": snapshot.options,
                "scenes": scenes,
                "unmapped_presets": unmapped,
            }
        )
    # YaHA explicitly treats an empty filter as exposing no entities. When merged
    # through HA packages this empty include list adds nothing to other filters.
    payload = {
        "filter": {"include_entities": list(entities)},
        "entity_config": entities,
    }
    return payload, reports, warnings, errors


def render_export(payload: dict[str, Any]) -> str:
    return (
        MARKER
        + "# Regenerate using wled_yaha.export_yaha_config.\n"
        + yaml.safe_dump(
            payload,
            allow_unicode=True,
            sort_keys=False,
            default_flow_style=False,
            width=100,
        )
    )


def validate_relative_path(path: str) -> str:
    """Only an explicit YAML file beneath the HA includes directory is allowed."""
    candidate = Path(path)
    if (
        candidate.is_absolute()
        or ".." in candidate.parts
        or len(candidate.parts) < 2
        or candidate.parts[0] != "includes"
        or candidate.suffix not in {".yaml", ".yml"}
    ):
        raise ValueError(
            "output_file должен быть YAML-файлом внутри includes/ без '..'."
        )
    return str(candidate)


def write_export(config_dir: str, relative_path: str, text: str) -> bool:
    """Atomically replace only a file owned by this generator. Return if changed."""
    validate_relative_path(relative_path)
    root = Path(config_dir).resolve()
    target = root / relative_path
    allowed_root = root / "includes"
    if target.is_symlink() or not target.resolve().is_relative_to(allowed_root):
        raise ValueError("Путь вывода или его родитель выходит за каталог includes/.")
    if target.exists():
        previous = target.read_text(encoding="utf-8")
        if not previous.startswith(MARKER):
            raise ValueError(
                f"Файл {relative_path} уже существует и создан не этим генератором. "
                "Выбери другое output_file; ручной файл не перезаписан."
            )
        if previous == text:
            return False
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary: str | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=target.parent,
            prefix=".wled_yaha_",
            delete=False,
        ) as handle:
            temporary = handle.name
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, target)
        temporary = None
    finally:
        if temporary is not None:
            Path(temporary).unlink(missing_ok=True)
    return True
